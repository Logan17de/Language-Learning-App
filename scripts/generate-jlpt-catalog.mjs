import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const [, , kanjiSource, grammarSource, jsonOutput, migrationOutput] = process.argv;

if (!kanjiSource || !grammarSource || !jsonOutput || !migrationOutput) {
  throw new Error(
    "Usage: node scripts/generate-jlpt-catalog.mjs "
    + "<kanji.txt> <grammar_patterns.txt> <catalog.json> <migration.sql>",
  );
}

const expectedCounts = {
  kanji: { N5: 80, N4: 170, N3: 370, N2: 380, N1: 1136 },
  grammar: { N5: 82, N4: 112, N3: 136, N2: 124, N1: 187 },
};

function parseCatalog(file, kind) {
  const records = [];
  let level = null;
  let position = 0;

  for (const rawLine of readFileSync(resolve(file), "utf8").split(/\r?\n/u)) {
    const line = rawLine.trim();
    const heading = line.match(/^JLPT (N[1-5]) \((\d+) /u);
    if (heading) {
      level = heading[1];
      position = 0;
      continue;
    }
    if (
      !level
      || !line
      || /^[-=]+$/u.test(line)
      || /^(?:Note:|This |Each |Exact |TOTAL:|JLPT )/u.test(line)
    ) {
      continue;
    }
    position += 1;
    records.push({
      level,
      position,
      [kind === "kanji" ? "character" : "pattern"]: line,
    });
  }

  const key = kind === "kanji" ? "character" : "pattern";
  const duplicates = records.filter(
    (record, index) => records.findIndex((candidate) => candidate[key] === record[key]) !== index,
  );
  if (duplicates.length > 0) {
    throw new Error(`${kind} source contains duplicate entries.`);
  }

  for (const [catalogLevel, expected] of Object.entries(expectedCounts[kind])) {
    const actual = records.filter((record) => record.level === catalogLevel).length;
    if (actual !== expected) {
      throw new Error(`${kind} ${catalogLevel} expected ${expected} records but found ${actual}.`);
    }
  }
  return records;
}

function sqlText(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function valuesSql(records, valueKey) {
  return records
    .map((record) =>
      `  (${sqlText(record[valueKey])}, '${record.level}'::public.jlpt_level, ${record.position})`)
    .join(",\n");
}

const kanji = parseCatalog(kanjiSource, "kanji");
const grammar = parseCatalog(grammarSource, "grammar");
const catalog = {
  schemaVersion: 1,
  source: "User-provided study-oriented JLPT classification",
  counts: {
    kanji: Object.fromEntries(
      Object.keys(expectedCounts.kanji).map((level) => [
        level,
        kanji.filter((record) => record.level === level).length,
      ]),
    ),
    grammar: Object.fromEntries(
      Object.keys(expectedCounts.grammar).map((level) => [
        level,
        grammar.filter((record) => record.level === level).length,
      ]),
    ),
  },
  kanji,
  grammar,
};

const migration = `-- Generated by scripts/generate-jlpt-catalog.mjs from the user-provided
-- N5-N1 study lists. These catalog tables intentionally store level placement
-- only. Gemini enriches selected entries into the reusable detailed libraries.

create table public.kanji_catalog (
  id uuid primary key default gen_random_uuid(),
  character text not null unique check (char_length(character) between 1 and 4),
  jlpt_level public.jlpt_level not null,
  source_order integer not null check (source_order > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (jlpt_level, source_order)
);

create table public.grammar_catalog (
  id uuid primary key default gen_random_uuid(),
  pattern text not null unique check (char_length(pattern) > 0),
  jlpt_level public.jlpt_level not null,
  source_order integer not null check (source_order > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (jlpt_level, source_order)
);

create index if not exists kanji_catalog_level_active_idx
  on public.kanji_catalog (jlpt_level, active, source_order);
create index if not exists grammar_catalog_level_active_idx
  on public.grammar_catalog (jlpt_level, active, source_order);

alter table public.kanji_catalog enable row level security;
alter table public.grammar_catalog enable row level security;

drop policy if exists kanji_catalog_authenticated_read on public.kanji_catalog;
create policy kanji_catalog_authenticated_read
  on public.kanji_catalog for select to authenticated
  using (active);

drop policy if exists grammar_catalog_authenticated_read on public.grammar_catalog;
create policy grammar_catalog_authenticated_read
  on public.grammar_catalog for select to authenticated
  using (active);

drop policy if exists kanji_catalog_staff_manage on public.kanji_catalog;
create policy kanji_catalog_staff_manage
  on public.kanji_catalog for all to authenticated
  using (public.has_app_role(array['admin','content_editor']::public.app_role[]))
  with check (public.has_app_role(array['admin','content_editor']::public.app_role[]));

drop policy if exists grammar_catalog_staff_manage on public.grammar_catalog;
create policy grammar_catalog_staff_manage
  on public.grammar_catalog for all to authenticated
  using (public.has_app_role(array['admin','content_editor']::public.app_role[]))
  with check (public.has_app_role(array['admin','content_editor']::public.app_role[]));

grant select on public.kanji_catalog, public.grammar_catalog to authenticated;
grant insert, update, delete on public.kanji_catalog, public.grammar_catalog to authenticated;

drop trigger if exists kanji_catalog_updated_at on public.kanji_catalog;
create trigger kanji_catalog_updated_at
  before update on public.kanji_catalog
  for each row execute function public.set_updated_at();

drop trigger if exists grammar_catalog_updated_at on public.grammar_catalog;
create trigger grammar_catalog_updated_at
  before update on public.grammar_catalog
  for each row execute function public.set_updated_at();

insert into public.kanji_catalog (character, jlpt_level, source_order)
values
${valuesSql(kanji, "character")}
on conflict (character) do update set
  jlpt_level = excluded.jlpt_level,
  source_order = excluded.source_order,
  active = true,
  updated_at = now();

insert into public.grammar_catalog (pattern, jlpt_level, source_order)
values
${valuesSql(grammar, "pattern")}
on conflict (pattern) do update set
  jlpt_level = excluded.jlpt_level,
  source_order = excluded.source_order,
  active = true,
  updated_at = now();
`;

mkdirSync(dirname(resolve(jsonOutput)), { recursive: true });
mkdirSync(dirname(resolve(migrationOutput)), { recursive: true });
writeFileSync(resolve(jsonOutput), `${JSON.stringify(catalog, null, 2)}\n`, "utf8");
writeFileSync(resolve(migrationOutput), migration, "utf8");

console.log(`Wrote ${kanji.length} kanji and ${grammar.length} grammar patterns.`);
